    public static final ConfigC2SConfigAcknowledgePayload                               INSTANCE;
    public static final Type<ConfigC2SConfigAcknowledgePayload>                         ID;
    public static final StreamCodec<FriendlyByteBuf, ConfigC2SConfigAcknowledgePayload> CODEC;

    //==================================================================================================================
    static
    {
        INSTANCE = new ConfigC2SConfigAcknowledgePayload();
        ID       = new Type<>(ConfigApiIds.Payload.CONFIG_C2S_CONFIG_ACK);
        CODEC    = StreamCodec.unit(INSTANCE);
    }
    
